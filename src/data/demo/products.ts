import type { OptionGroup, OptionValue, Product } from '../types';

const opt = (ids: string[], unavailable: string[] = []): OptionValue[] =>
  ids.map((id) => ({ id, label: id, available: !unavailable.includes(id) }));

const sizes = (ids: string[], unavailable: string[] = []): OptionGroup => ({
  id: 'size',
  label: 'Розмір',
  values: opt(ids, unavailable),
});

const colors = (values: OptionValue[]): OptionGroup => ({ id: 'color', label: 'Колір', values });

const volume = (values: [number, number, boolean?, number?][]): OptionGroup => ({
  id: 'volume',
  label: "Об'єм",
  values: values.map(([ml, price, available = true, oldPrice]) => ({
    id: `${ml}`,
    label: `${ml} мл`,
    price,
    oldPrice,
    available,
  })),
});

